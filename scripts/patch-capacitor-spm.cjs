"use strict";
/**
 * Capacitor 6 iOS SPM needs Package.swift per plugin and pure-Swift registration
 * (no Obj-C .m CAP_PLUGIN macros — SPM rejects mixed-language targets).
 */
const fs = require("fs");
const path = require("path");

const root = path.resolve(__dirname, "..");

function packageSwift({ name, target, pluginPath, frameworks, exclude }) {
  const excludeBlock = exclude.length
    ? `,
            exclude: [${exclude.map((f) => `"${f}"`).join(", ")}]`
    : "";
  const linker = frameworks.length
    ? `,
            linkerSettings: [
                ${frameworks.map((f) => `.linkedFramework("${f}")`).join(",\n                ")}
            ]`
    : "";
  return `// swift-tools-version: 5.9
// AXIS: generated by scripts/patch-capacitor-spm.cjs
import PackageDescription

let package = Package(
    name: "${name}",
    platforms: [.iOS(.v13)],
    products: [
        .library(
            name: "${name}",
            targets: ["${target}"])
    ],
    dependencies: [
        .package(url: "https://github.com/ionic-team/capacitor-swift-pm.git", from: "6.0.0")
    ],
    targets: [
        .target(
            name: "${target}",
            dependencies: [
                .product(name: "Capacitor", package: "capacitor-swift-pm"),
                .product(name: "Cordova", package: "capacitor-swift-pm")
            ],
            path: "${pluginPath}"${excludeBlock}${linker})
    ]
)
`;
}

function disableObjcBridge(pluginDir, baseName) {
  for (const ext of [".m", ".h"]) {
    const src = path.join(pluginDir, `${baseName}${ext}`);
    const dst = path.join(pluginDir, `${baseName}${ext}.axis-spm-bak`);
    if (fs.existsSync(src) && !fs.existsSync(dst)) {
      fs.renameSync(src, dst);
    }
  }
}

function patchSwiftBridged(filePath, className, jsName, methods) {
  if (!fs.existsSync(filePath)) return false;
  const text = fs.readFileSync(filePath, "utf8");
  if (text.includes("CAPBridgedPlugin")) return false;
  const re = new RegExp(
    `@objc\\(${className}\\)\\s*\\npublic class ${className}: CAPPlugin \\{`
  );
  if (!re.test(text)) {
    console.warn("patch-capacitor-spm: class pattern not found in", filePath);
    return false;
  }
  const methodLines = methods
    .map((m) => `        CAPPluginMethod(name: "${m}", returnType: CAPPluginReturnPromise)`)
    .join(",\n");
  const bridged = `@objc(${className})
public class ${className}: CAPPlugin, CAPBridgedPlugin {
    public let identifier = "${className}"
    public let jsName = "${jsName}"
    public let pluginMethods: [CAPPluginMethod] = [
${methodLines}
    ]

`;
  fs.writeFileSync(filePath, text.replace(re, bridged), "utf8");
  return true;
}

const patches = [
  {
    dir: path.join(root, "node_modules", "@capacitor-community", "keep-awake"),
    name: "CapacitorCommunityKeepAwake",
    target: "KeepAwakePlugin",
    pluginPath: "ios/Plugin",
    frameworks: [],
    objcBase: "KeepAwakePlugin",
    exclude: ["KeepAwakePlugin.m.axis-spm-bak", "KeepAwakePlugin.h.axis-spm-bak", "Info.plist"],
    swiftFile: "ios/Plugin/KeepAwakePlugin.swift",
    className: "KeepAwakePlugin",
    jsName: "KeepAwake",
    methods: ["keepAwake", "allowSleep", "isSupported", "isKeptAwake"],
  },
  {
    dir: path.join(root, "node_modules", "@perfood", "capacitor-healthkit"),
    name: "PerfoodCapacitorHealthkit",
    target: "CapacitorHealthkitPlugin",
    pluginPath: "ios/Plugin",
    frameworks: ["HealthKit"],
    objcBase: "CapacitorHealthkitPlugin",
    exclude: [
      "CapacitorHealthkitPlugin.m.axis-spm-bak",
      "CapacitorHealthkitPlugin.h.axis-spm-bak",
      "Info.plist",
    ],
    swiftFile: "ios/Plugin/CapacitorHealthkitPlugin.swift",
    className: "CapacitorHealthkitPlugin",
    jsName: "CapacitorHealthkit",
    methods: [
      "requestAuthorization",
      "queryHKitSampleType",
      "isAvailable",
      "multipleQueryHKitSampleType",
      "isEditionAuthorized",
      "multipleIsEditionAuthorized",
    ],
  },
];

let wrote = 0;
for (const p of patches) {
  if (!fs.existsSync(p.dir)) {
    console.warn("patch-capacitor-spm: skip (not installed):", p.dir);
    continue;
  }
  disableObjcBridge(path.join(p.dir, p.pluginPath), p.objcBase);
  patchSwiftBridged(
    path.join(p.dir, p.swiftFile),
    p.className,
    p.jsName,
    p.methods
  );
  const out = path.join(p.dir, "Package.swift");
  fs.writeFileSync(
    out,
    packageSwift({
      name: p.name,
      target: p.target,
      pluginPath: p.pluginPath,
      frameworks: p.frameworks,
      exclude: p.exclude,
    }),
    "utf8"
  );
  wrote += 1;
  console.log("patch-capacitor-spm:", path.relative(root, out));
}

if (!wrote) {
  console.warn("patch-capacitor-spm: no plugins patched — run npm install first");
}
